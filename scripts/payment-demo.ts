import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import { createRuntime } from '../src/economics/runtime.js';
import { buildServer } from '../src/server.js';
import { fixture } from '../src/sim/assembly.js';
import { startLocalNode, freePort, rpc } from './local-node.js';
const directory = await mkdtemp(join(tmpdir(), 'eb-payments-'));
const node = await startLocalNode(await freePort());
const runtime = await createRuntime('local', directory, node.url);
const app = buildServer(runtime.store, runtime.orders);
const headers = { 'x-experiencebridge-client': 'local-ui' };
const post = (url: string, payload: object, token?: string) => app.inject({ method: 'POST', url, payload, headers: { ...headers, ...(token ? { authorization: `Bearer ${token}` } : {}) } });
try {
 await rpc(node.url, 'anvil_setBalance', [runtime.gateway.buyerAddress, '0x8ac7230489e80000']);
 assert.equal((await post('/api/demo/publish', {})).statusCode, 200);
 assert.equal((await post('/simulation/run', { context: fixture })).json().outcome, 'slip');
 assert.equal((await app.inject({method:'POST',url:'/api/orders',payload:{}})).statusCode,403);
 assert.equal((await app.inject({url:'/api/config',headers:{host:'attacker.example'}})).statusCode,403);
 assert.equal((await app.inject({url:'/api/config',headers:{origin:'https://attacker.example'}})).statusCode,403);
 const publicRecord=(await app.inject('/experiences/exp-001')).json();
 assert.equal(publicRecord.advisory,undefined);
 const publicQuery=(await post('/experiences/query',{task:'connector_insertion',context:fixture,use:'synthetic-demo'})).json();
 assert.equal(publicQuery.results[0].advisory,null);
 assert.equal((await post('/simulation/run',{context:fixture,experienceId:'exp-001'})).statusCode,402);
 assert.equal((await post('/api/orders', { experienceId: 'exp-001', context: { ...fixture, gripper: 'vacuum-v2' }, idempotencyKey: randomUUID() })).statusCode, 422);
 const quoted = await post('/api/orders', { experienceId: 'exp-001', context: fixture, idempotencyKey: randomUUID() });
 assert.equal(quoted.statusCode, 200, quoted.body);
 const { order, token } = quoted.json();
 assert.equal((await post(`/api/orders/${order.id}/run`, {}, token)).statusCode, 402);
 const paid = await post(`/api/orders/${order.id}/pay`, {}, token);
 assert.equal(paid.statusCode, 200, paid.body); assert.ok(paid.json().order.transactionHash);
 const retry = await post(`/api/orders/${order.id}/pay`, {}, token);
 assert.equal(retry.json().order.transactionHash, paid.json().order.transactionHash);
 await rpc(node.url, 'anvil_mine', ['0x5']);
 const checked = await post(`/api/orders/${order.id}/verify`, {}, token);
 assert.equal(checked.json().order.state, 'confirmed', checked.body);
 const recovered = await post(`/api/orders/${order.id}/run`, {}, token);
 assert.equal(recovered.json().outcome, 'success', recovered.body);
 const balances = await runtime.gateway.balances(); assert.equal(balances.seller, '0.001');
 console.log(JSON.stringify({ network: 'local EVM only, not Agung', chainId: 31337, transactionHash: paid.json().order.transactionHash, payment: checked.json().order.state, sellerReceived: balances.seller + ' local ETH', baseline: 'slip', recovery: recovered.json().outcome, incompatibleQuote: 'rejected before payment', retry: 'same signed transaction, seller paid once' }, null, 2));
} finally { await app.close(); await runtime.close(); await node.stop(); }
